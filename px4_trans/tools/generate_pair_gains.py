"""Generate fixed-geometry pair LQI at configuration time, never in the flight loop."""
from pathlib import Path
import numpy as np
import yaml
from scipy.linalg import expm, solve_discrete_are

ROOT = Path(__file__).resolve().parents[2]
pair = yaml.safe_load((ROOT/'px4_trans/configs/composite_controller.yaml').read_text())
config = yaml.safe_load((ROOT/pair['unit_controller']).read_text())['params']['lqi']
# Read the same physical baseline used by the single-aircraft payload.
physical = yaml.safe_load((ROOT/pair['unit_model']).read_text())
mass, arm = physical['body']['mass']['value'], float(pair['arm_m'])
unit = np.array(physical['body']['inertia_diagonal_b']['value'])
yaw = np.radians(pair['installation_yaw_deg'])
assert mass > 0 and arm > 0 and np.isfinite(arm)
assert len(yaw) == 2 and np.isfinite(yaw).all()
inertia = np.zeros((3,3))
for angle, y in zip(yaw,[arm,-arm]):
    c,s=np.cos(angle),np.sin(angle)
    rotation=np.array([[c,-s,0],[s,c,0],[0,0,1]])
    r=np.array([0,y,0])
    inertia += rotation@np.diag(unit)@rotation.T + mass*(r@r*np.eye(3)-np.outer(r,r))
assert np.max(abs(inertia-np.diag(np.diag(inertia))))<1e-10, "demo requires diagonal composite inertia"
gain=np.zeros((3,8))
poles=[]
for axis, indices in enumerate([[0,2,5],[1,3,6],[4,7]]):
    n=len(indices)
    a=np.zeros((n,n)); b=np.zeros((n,1))
    if n==3: a[0,1]=a[2,0]=1; b[1,0]=1/(unit[1] if axis==1 else inertia[axis,axis])
    else: a[1,0]=1; b[0,0]=1/inertia[axis,axis]
    z=expm(np.block([[a,b],[np.zeros((1,n+1))]])*.002)
    ad,bd=z[:n,:n],z[:n,n:]
    q=np.diag(1/np.array(config['state_scales'])[indices]**2)
    r=np.array([[config['input_weight_scale']/config['input_scales'][axis]**2]])
    p=solve_discrete_are(ad,bd,q,r)
    k=np.linalg.solve(r+bd.T@p@bd,bd.T@p@ad)
    poles.extend(np.linalg.eigvals(ad-bd@k))
    gain[axis,indices]=k[0]*(inertia[1,1]/unit[1] if axis==1 else 1)
assert max(abs(np.array(poles)))<1
fmt=lambda xs: ', '.join(f'{float(x):.10e}f' for x in xs)
text='// Generated by tools/generate_pair_gains.py; geometry changes require regeneration.\n#pragma once\nnamespace pair_gains {\n'
text+=f'constexpr float arm={arm}f;\nconstexpr float yaw[2]={{ {fmt(yaw)} }};\n'
text+=f'constexpr float inertia[3]={{ {fmt(np.diag(inertia))} }};\n'
text+=f'constexpr float gain[24]={{ {fmt(gain.flatten())} }};\n'
text+='constexpr float integral_limit[3]={.20f,.20f,.80f};\n}\n'
(ROOT/'px4_trans/px4/src/modules/comp_control/PairGains.hpp').write_text(text)
print('pair inertia:',np.diag(inertia),'closed-loop pole radius:',max(abs(np.array(poles))))

# Export the same unit-model geometry for runtime wrench residual diagnostics.
aero=physical['aerodynamics']
# Runtime diagnostic equations specialize the existing baseline; reject changes
# that would invalidate that specialization instead of silently misreporting.
assert np.allclose(physical['body']['center_of_mass_b']['value'], [0,0,0])
assert np.allclose(aero['neutral_thrust_direction_b']['value'], [0,0,-1])
assert np.allclose(aero['direct_thrust_center_b']['value'], [0,0,0])
assert len(physical['servos'][0]['pwm_angle_table']['value']) == 3
for servo in physical['servos']:
    assert servo['pwm_angle_table'] == physical['servos'][0]['pwm_angle_table']
for grid in aero['grids']:
    assert grid['vector_deflection']['offset']['value'] == 0
    assert abs(grid['deflection_axis_b']['value'][2]) < 1e-10
    assert grid['self_attenuation_curve'] == aero['grids'][0]['self_attenuation_curve']
assert len(aero['grids'][0]['self_attenuation_curve']['value']) == 2
arrays={
    'partition': [v['value'] for v in aero['thrust_partition'].values()],
    'grid_arm': [v for g in aero['grids'] for v in g['aerodynamic_center_b']['value']],
    'axis': [v for g in aero['grids'] for v in g['deflection_axis_b']['value']],
    'coupling': np.array(aero['coupling_attenuation']['value']).flatten(),
    'servo_table': np.array(physical['servos'][0]['pwm_angle_table']['value']).flatten(),
    'attenuation_table': np.array(aero['grids'][0]['self_attenuation_curve']['value']).flatten(),
    'vector_gain': [g['vector_deflection']['gain']['value'] for g in aero['grids']],
}
header='// Generated from the single-aircraft physical YAML.\n#pragma once\nnamespace pair_plant {\n'
for name, data in arrays.items():
    header+=f'constexpr float {name}[{len(data)}]={{ {fmt(data)} }};\n'
header+='}\n'
(ROOT/'px4_trans/px4/src/modules/comp_control/PairPlant.hpp').write_text(header)
